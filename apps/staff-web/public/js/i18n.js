const LANG_KEY = "mpizza.staff.lang";

function savedLang() {
  try {
    const v = window.localStorage.getItem(LANG_KEY);
    return v === "en" || v === "ar" ? v : "ar";
  } catch {
    return "ar";
  }
}

export let lang = savedLang();

export function t(key) {
  return STRINGS[lang]?.[key] ?? STRINGS.ar[key] ?? key;
}

/** Applies direction/lang to the document and fills every [data-i18n] element. */
export function applyLanguage() {
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  for (const el of document.querySelectorAll("[data-i18n]")) el.textContent = t(el.dataset.i18n);
  document.title = `${t("appName")} - ${document.title.split(" - ").pop() ?? ""}`.replace(/ - $/, "");
}

export function toggleLanguage() {
  lang = lang === "ar" ? "en" : "ar";
  try {
    window.localStorage.setItem(LANG_KEY, lang);
  } catch {
    // Preference simply isn't remembered.
  }
  applyLanguage();
}
